package lk.hms.modules.appointments.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lk.hms.modules.departments.entity.Department;
import lk.hms.modules.doctors.entity.Doctor;
import lk.hms.modules.patients.entity.Patient;
import lombok.Getter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;
import lombok.NoArgsConstructor;
import lombok.Setter;

import java.time.Instant;
import java.time.LocalDateTime;
import java.util.EnumSet;
import java.util.Map;
import java.util.Set;

@Entity
@Table(name = "appointments")
@Getter
@Setter
@NoArgsConstructor
public class Appointment {

    public enum Type { CONSULTATION, FOLLOW_UP, WALK_IN }

    public enum Status {
        PENDING, CONFIRMED, CHECKED_IN, IN_PROGRESS, COMPLETED, CANCELLED, NO_SHOW;

        /** The appointment state machine (docs/01 §2D). Anything not listed here is rejected with 409. */
        private static final Map<Status, Set<Status>> ALLOWED = Map.of(
                PENDING, EnumSet.of(CONFIRMED, CANCELLED),
                CONFIRMED, EnumSet.of(CHECKED_IN, CANCELLED, NO_SHOW),
                CHECKED_IN, EnumSet.of(IN_PROGRESS),
                IN_PROGRESS, EnumSet.of(COMPLETED),
                COMPLETED, EnumSet.noneOf(Status.class),
                CANCELLED, EnumSet.noneOf(Status.class),
                NO_SHOW, EnumSet.noneOf(Status.class));

        public boolean canMoveTo(Status next) {
            return ALLOWED.get(this).contains(next);
        }

        /** Holds the slot (counts against capacity and the doctor's unique slot). */
        public boolean isLive() {
            return this != CANCELLED && this != NO_SHOW;
        }
    }

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "appointment_no", nullable = false, unique = true, length = 20, updatable = false)
    private String appointmentNo;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "patient_id")
    private Patient patient;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "doctor_id")
    private Doctor doctor;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "department_id")
    private Department department;

    /** UTC. */
    @Column(name = "slot_start", nullable = false)
    private LocalDateTime slotStart;

    /** UTC. */
    @Column(name = "slot_end", nullable = false)
    private LocalDateTime slotEnd;

    @Column(name = "token_no", nullable = false, columnDefinition = "smallint")
    private int tokenNo;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Type type = Type.CONSULTATION;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Status status = Status.PENDING;

    private String reason;

    @Column(name = "cancel_reason")
    private String cancelReason;

    @Column(name = "rescheduled_from_id")
    private Long rescheduledFromId;

    @Column(name = "booked_by")
    private Long bookedBy;

    @Column(name = "confirmed_at")
    private Instant confirmedAt;

    @Column(name = "checked_in_at")
    private Instant checkedInAt;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "completed_at")
    private Instant completedAt;

    @Column(name = "cancelled_at")
    private Instant cancelledAt;

    /** Generated by MySQL (NULL when cancelled / no-show); read-only here. */
    @Column(name = "active_slot_start", insertable = false, updatable = false)
    private LocalDateTime activeSlotStart;

    @Version
    private long version;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}
