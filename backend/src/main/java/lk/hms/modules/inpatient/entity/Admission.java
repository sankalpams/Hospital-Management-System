package lk.hms.modules.inpatient.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.math.BigDecimal;
import java.time.Instant;

@Entity
@Table(name = "admissions")
@Getter
@Setter
@NoArgsConstructor
public class Admission {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    public enum Status { REQUESTED, ADMITTED, DISCHARGED, CANCELLED }

    @Column(name = "admission_no", nullable = false, unique = true, length = 20, updatable = false)
    private String admissionNo;

    @Column(name = "patient_id", nullable = false)
    private Long patientId;

    @Column(name = "attending_doctor_id", nullable = false)
    private Long attendingDoctorId;

    @Column(name = "department_id", nullable = false)
    private Long departmentId;

    @Column(name = "admission_type", nullable = false, length = 15)
    private String admissionType;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 15)
    private Status status = Status.REQUESTED;

    @Column(nullable = false, length = 500)
    private String reason;

    @Column(name = "requested_by")
    private Long requestedBy;

    @Column(name = "requested_at", nullable = false)
    private Instant requestedAt;

    @Column(name = "admitted_at")
    private Instant admittedAt;

    @Column(name = "discharged_at")
    private Instant dischargedAt;

    @Column(name = "discharge_type", length = 20)
    private String dischargeType;

    @Column(name = "discharge_summary", columnDefinition = "text")
    private String dischargeSummary;

    /** Generated by MySQL (one live admission per patient); read-only here. */
    @Column(name = "active_patient_id", insertable = false, updatable = false)
    private Long activePatientId;

    @Version
    private long version;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;
}
