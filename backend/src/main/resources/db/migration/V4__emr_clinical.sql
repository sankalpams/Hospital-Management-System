-- V4__emr_clinical.sql
-- Electronic Medical Records (EMR): encounters, vitals, diagnoses, ICD-10, prescriptions, clinical notes, drug interactions

-- 1. Sequences
CREATE SEQUENCE IF NOT EXISTS encounter_number_seq START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS rx_number_seq START WITH 1 INCREMENT BY 1;

-- 2. ICD-10 Reference Table
CREATE TABLE IF NOT EXISTS icd10_codes (
    code VARCHAR(16) PRIMARY KEY,
    description TEXT NOT NULL,
    category VARCHAR(128) NOT NULL,
    is_common BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_icd10_category ON icd10_codes(category);

-- 3. Drug Interactions Reference Table
CREATE TABLE IF NOT EXISTS drug_interactions (
    id UUID PRIMARY KEY,
    drug_a VARCHAR(255) NOT NULL,
    drug_b VARCHAR(255) NOT NULL,
    severity VARCHAR(24) NOT NULL, -- MAJOR, MODERATE, MINOR
    description TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_drug_interactions_pair ON drug_interactions(drug_a, drug_b);

-- 4. Encounters Table
CREATE TABLE IF NOT EXISTS encounters (
    id UUID PRIMARY KEY,
    encounter_number VARCHAR(32) NOT NULL UNIQUE,
    appointment_id UUID REFERENCES appointments(id),
    patient_id UUID NOT NULL REFERENCES patients(id),
    doctor_id UUID NOT NULL REFERENCES doctors(id),
    encounter_type VARCHAR(24) NOT NULL DEFAULT 'OPD', -- OPD, IPD, EMERGENCY
    status VARCHAR(24) NOT NULL DEFAULT 'IN_PROGRESS', -- DRAFT, IN_PROGRESS, SIGNED
    chief_complaint TEXT,
    history_of_presenting_illness TEXT,
    examination_notes TEXT,
    treatment_plan TEXT,
    follow_up_date DATE,
    signed_at TIMESTAMPTZ,
    signed_by VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    version BIGINT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_encounters_patient_id ON encounters(patient_id);
CREATE INDEX idx_encounters_doctor_id ON encounters(doctor_id);
CREATE INDEX idx_encounters_appointment_id ON encounters(appointment_id);
CREATE INDEX idx_encounters_status ON encounters(status);

-- 5. Vitals Table
CREATE TABLE IF NOT EXISTS vitals (
    id UUID PRIMARY KEY,
    encounter_id UUID NOT NULL REFERENCES encounters(id),
    patient_id UUID NOT NULL REFERENCES patients(id),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    systolic_bp INT,
    diastolic_bp INT,
    pulse_rate INT,
    temperature_celsius NUMERIC(4, 1),
    respiratory_rate INT,
    spo2 NUMERIC(4, 1),
    weight_kg NUMERIC(5, 2),
    height_cm NUMERIC(5, 2),
    bmi NUMERIC(4, 1),
    is_bp_abnormal BOOLEAN DEFAULT FALSE,
    is_pulse_abnormal BOOLEAN DEFAULT FALSE,
    is_temp_abnormal BOOLEAN DEFAULT FALSE,
    is_spo2_abnormal BOOLEAN DEFAULT FALSE,
    is_bmi_abnormal BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    version BIGINT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_vitals_encounter_id ON vitals(encounter_id);
CREATE INDEX idx_vitals_patient_id ON vitals(patient_id);

-- 6. Diagnoses Table
CREATE TABLE IF NOT EXISTS diagnoses (
    id UUID PRIMARY KEY,
    encounter_id UUID NOT NULL REFERENCES encounters(id),
    patient_id UUID NOT NULL REFERENCES patients(id),
    icd10_code VARCHAR(16) NOT NULL REFERENCES icd10_codes(code),
    diagnosis_type VARCHAR(24) NOT NULL DEFAULT 'PRIMARY', -- PRIMARY, SECONDARY, PROVISIONAL, DIFFERENTIAL
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    version BIGINT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_diagnoses_encounter_id ON diagnoses(encounter_id);
CREATE INDEX idx_diagnoses_patient_id ON diagnoses(patient_id);
CREATE INDEX idx_diagnoses_icd10_code ON diagnoses(icd10_code);

-- 7. Prescriptions Table
CREATE TABLE IF NOT EXISTS prescriptions (
    id UUID PRIMARY KEY,
    prescription_number VARCHAR(32) NOT NULL UNIQUE,
    encounter_id UUID NOT NULL REFERENCES encounters(id),
    patient_id UUID NOT NULL REFERENCES patients(id),
    doctor_id UUID NOT NULL REFERENCES doctors(id),
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE, DISPENSED, CANCELLED
    notes TEXT,
    safety_warnings_acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    safety_warnings_acknowledged_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    version BIGINT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_prescriptions_patient_id ON prescriptions(patient_id);
CREATE INDEX idx_prescriptions_encounter_id ON prescriptions(encounter_id);
CREATE INDEX idx_prescriptions_doctor_id ON prescriptions(doctor_id);

-- 8. Prescription Items Table
CREATE TABLE IF NOT EXISTS prescription_items (
    id UUID PRIMARY KEY,
    prescription_id UUID NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
    drug_name VARCHAR(255) NOT NULL,
    dosage VARCHAR(64) NOT NULL,
    frequency VARCHAR(64) NOT NULL,
    duration VARCHAR(64) NOT NULL,
    route VARCHAR(64) NOT NULL DEFAULT 'Oral',
    instructions TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    version BIGINT NOT NULL DEFAULT 0,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_rx_items_prescription_id ON prescription_items(prescription_id);

-- 9. Clinical Notes (Versioned / Addenda) Table
CREATE TABLE IF NOT EXISTS clinical_notes (
    id UUID PRIMARY KEY,
    encounter_id UUID NOT NULL REFERENCES encounters(id),
    patient_id UUID NOT NULL REFERENCES patients(id),
    note_type VARCHAR(32) NOT NULL DEFAULT 'PROGRESS_NOTE', -- PROGRESS_NOTE, SOAP, DISCHARGE_SUMMARY, CONSULT_NOTE, ADDENDUM
    content TEXT NOT NULL,
    version INT NOT NULL DEFAULT 1,
    is_signed BOOLEAN NOT NULL DEFAULT FALSE,
    signed_at TIMESTAMPTZ,
    signed_by VARCHAR(64),
    parent_note_id UUID REFERENCES clinical_notes(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_clinical_notes_encounter_id ON clinical_notes(encounter_id);
CREATE INDEX idx_clinical_notes_patient_id ON clinical_notes(patient_id);
CREATE INDEX idx_clinical_notes_parent_note_id ON clinical_notes(parent_note_id);


